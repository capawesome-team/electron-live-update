/**
 * Configuration of the live update engine.
 *
 * The engine is host-agnostic: everything that depends on the runtime
 * (paths, version information, platform identity) is injected.
 *
 * @since 0.1.0
 */
export interface LiveUpdateEngineConfig {
  /**
   * The app ID is used to identify the app when using
   * [Capawesome Cloud](https://capawesome.io/cloud/).
   *
   * This is **NOT** the same as the app identifier (e.g. `com.example.app`).
   * This is a unique identifier generated by Capawesome Cloud
   * (e.g. `6e351b4f-69a7-415e-a057-4567df7ffe94`).
   *
   * Required for `sync()` and `fetchLatestBundle()`. Not required when
   * bundles are managed manually via `downloadBundle()`.
   *
   * @since 0.1.0
   * @example '6e351b4f-69a7-415e-a057-4567df7ffe94'
   */
  appId?: string;
  /**
   * Whether or not to automatically block bundles that have been rolled back.
   *
   * When enabled, the engine will automatically block bundles that caused
   * a rollback (up to 100 bundles). When the limit is reached, the oldest
   * blocked bundle is unblocked. Blocked bundles will be skipped in future
   * sync operations.
   *
   * **Attention**: This option has no effect if `readyTimeout` is set to `0`.
   *
   * @since 0.1.0
   * @default false
   */
  autoBlockRolledBackBundles?: boolean;
  /**
   * Whether or not to automatically delete unused bundles.
   *
   * When enabled, the engine will automatically delete unused bundles after
   * calling `ready()`. The current bundle, the next bundle and the last
   * bundle that successfully signaled readiness are never deleted.
   *
   * @since 0.1.0
   * @default false
   */
  autoDeleteBundles?: boolean;
  /**
   * The directory where the engine stores its bundles and state.
   *
   * The directory is created if it does not exist. It must be writable
   * and should be excluded from any file synchronization (e.g. backups).
   *
   * @since 0.1.0
   */
  dataDirectory: string;
  /**
   * The absolute path to the directory containing the default bundle
   * (the web assets packaged with the app).
   *
   * Used by `manifest` (delta) updates to reuse unchanged files of the
   * packaged default bundle when it is the current bundle. If not set,
   * a delta update on top of the default bundle downloads all files.
   *
   * @since 0.1.0
   */
  defaultBundlePath?: string;
  /**
   * The default channel of the app.
   *
   * This can be overridden by `setChannel()` or the `channel` parameter
   * of `sync()`.
   *
   * @since 0.1.0
   * @example 'production'
   */
  defaultChannel?: string;
  /**
   * The timeout in milliseconds for HTTP requests.
   *
   * @since 0.1.0
   * @default 60000
   */
  httpTimeout?: number;
  /**
   * A custom logger.
   *
   * @since 0.1.0
   * @default console
   */
  logger?: LiveUpdateLogger;
  /**
   * The operating system version reported to Capawesome Cloud.
   *
   * @since 0.1.0
   */
  osVersion: string;
  /**
   * The platform identifier reported to Capawesome Cloud.
   *
   * @since 0.1.0
   */
  platform: string;
  /**
   * The plugin version reported to Capawesome Cloud (the `pluginVersion`
   * request parameter).
   *
   * Defaults to `sdkVersion`. The standalone Electron SDK reports the
   * engine version; a Capacitor adapter reports the plugin package
   * version.
   *
   * @since 0.1.0
   */
  pluginVersion?: string;
  /**
   * The public key to verify the integrity of the bundle.
   *
   * The public key must be a PEM-encoded RSA public key.
   *
   * @since 0.1.0
   */
  publicKey?: string;
  /**
   * The timeout in milliseconds to wait for the app to be ready
   * before rolling back to the previous bundle.
   *
   * It is strongly **recommended** to configure this option (e.g. `10000` ms)
   * so that the SDK can roll back in case of problems: if configured, the
   * app must call `ready()` within this timeout after every start or reload
   * of a live update bundle. This also enables the kill-safe boot rollback:
   * a marker is persisted before a new bundle loads and is only cleared by
   * `ready()`, so a crash or kill during boot is detected on the next start.
   *
   * Set to `0` to disable rollback protection.
   *
   * @since 0.1.0
   * @default 0
   * @example 10000
   */
  readyTimeout?: number;
  /**
   * The runtime identifier reported to Capawesome Cloud.
   *
   * If not set, no runtime is reported and the server assumes its
   * default runtime.
   *
   * @since 0.1.0
   * @example 'electron'
   */
  runtime?: string;
  /**
   * The version of the SDK reported to Capawesome Cloud.
   *
   * @since 0.1.0
   */
  sdkVersion: string;
  /**
   * The API domain of the [Capawesome Cloud](https://cloud.capawesome.io)
   * server **without** scheme or path.
   *
   * @since 0.1.0
   * @default 'api.cloud.capawesome.io'
   * @example 'api.cloud.capawesome.eu'
   */
  serverDomain?: string;
  /**
   * The version code of the app reported to Capawesome Cloud.
   *
   * @since 0.1.0
   * @example '1'
   */
  versionCode: string;
  /**
   * The version name of the app reported to Capawesome Cloud.
   *
   * @since 0.1.0
   * @example '1.0.0'
   */
  versionName: string;
}

